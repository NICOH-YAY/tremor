# Extract only BEX text; this port intentionally does not load gameplay Dehacked patches.
from pathlib import Path
import struct,re,json
b=Path('public/wad/freedoom1.wad').read_bytes();n,o=struct.unpack_from('<ii',b,4)
for i in range(n):
 p,z,name=struct.unpack_from('<ii8s',b,o+i*16)
 if name.rstrip(b'\0')==b'DEHACKED':text=b[p:p+z].decode('ascii')
text=text.split('[STRINGS]',1)[1];text=re.sub(r'\\\r?\n\s*','',text)
rows=[]
for line in text.splitlines():
 m=re.match(r'^([A-Z][A-Z0-9_]*)\s*=\s*(.*)',line)
 if m:
  name,value=m.groups();value=value.replace('\\n','\n').replace('\\t','\t').replace('\\\\','\\')
  rows.append('#ifdef '+name+'\n{'+name+','+json.dumps(value)+'},\n#endif')
Path('engine/tremor/freedoom_strings.h').write_text('/* Freedoom Phase 1 v0.13.0 BEX text, BSD-3-Clause. Contributors to Freedoom.\n   Generated by scripts/build-freedoom-strings.py. Retain public/wad/FREEDOOM-LICENSE.txt. */\n'+ '\n'.join(rows)+'\n')
